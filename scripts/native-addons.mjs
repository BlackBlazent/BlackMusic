#!/usr/bin/env node
/**
 * Optional MOBILE native add-ons (FFmpeg audio library + whisper.cpp). Called by scripts/android-post-init.mjs.
 * It looks for what YOU put in `native/` and wires in only what exists — a build with an empty `native/` folder works
 * exactly as before (the app then says "add-on not installed" where the feature needs it). Steps: docs/MOBILE_NATIVE.md.
 *
 *   native/android/ffmpeg-kit/*.aar      FFmpegKit audio AAR (LGPL variant)        -> window.BMNative.ffmpegRun
 *   native/android/whisper.cpp/          whisper.cpp source tree (has CMakeLists)   -> window.BMNative.whisperTranscribe
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");

const FFMPEG_CODE = `val a = JSONArray(argsJson)
                val args = Array(a.length()) { a.getString(it) }
                val session = com.arthenica.ffmpegkit.FFmpegKit.executeWithArguments(args)
                out.put("code", session.returnCode?.value ?: -1).put("stderr", (session.allLogsAsString ?: "").takeLast(2000))`;
const WHISPER_CODE = `val segs = WhisperNative.transcribe(modelPath, wavPath, language)
                out.put("segments", segs)`;

const jniMangle = (pkg) => pkg.replaceAll("_", "_1").replaceAll(".", "_");

export function installNativeAddons({ pkg, srcMain, appDir, javaDir }) {
  const nativeDir = join(repoRoot, "native", "android");
  const aar = existsSync(join(nativeDir, "ffmpeg-kit")) ? readdirSync(join(nativeDir, "ffmpeg-kit")).find((f) => f.endsWith(".aar")) : undefined;
  const whisperDir = join(nativeDir, "whisper.cpp");
  const hasWhisper = existsSync(join(whisperDir, "CMakeLists.txt"));
  const hasFfmpeg = Boolean(aar);

  // ---- NativeBridge.kt (always) -----------------------------------------------------------------------------------------------
  let bridge = readFileSync(join(here, "android", "NativeBridge.kt.tpl"), "utf8").replaceAll("__PKG__", pkg);
  bridge = bridge.replace("__HAS_FFMPEG__", String(hasFfmpeg)).replace("__HAS_WHISPER__", String(hasWhisper));
  if (hasFfmpeg) bridge = bridge.replace(/\/\*FFMPEG_BEGIN\*\/[\s\S]*?\/\*FFMPEG_END\*\//, FFMPEG_CODE);
  if (hasWhisper) bridge = bridge.replace(/\/\*WHISPER_BEGIN\*\/[\s\S]*?\/\*WHISPER_END\*\//, WHISPER_CODE);
  writeFileSync(join(javaDir, "NativeBridge.kt"), bridge);

  const gradleFile = [join(appDir, "build.gradle.kts"), join(appDir, "build.gradle")].find(existsSync);
  let gradle = gradleFile ? readFileSync(gradleFile, "utf8") : "";
  const proguard = join(appDir, "proguard-rules.pro");
  const keep = [];

  // ---- FFmpegKit (prebuilt AAR) -----------------------------------------------------------------------------------------------
  if (hasFfmpeg && gradleFile && !gradle.includes("BM_FFMPEG_KIT")) {
    mkdirSync(join(appDir, "libs"), { recursive: true });
    copyFileSync(join(nativeDir, "ffmpeg-kit", aar), join(appDir, "libs", aar));
    const dep = gradleFile.endsWith(".kts")
      ? `    implementation(files("libs/${aar}")) // BM_FFMPEG_KIT\n    implementation("com.arthenica:smart-exception-java:0.2.1")\n`
      : `    implementation files('libs/${aar}') // BM_FFMPEG_KIT\n    implementation 'com.arthenica:smart-exception-java:0.2.1'\n`;
    gradle = gradle.replace(/dependencies\s*\{/, (m) => `${m}\n${dep}`);
    keep.push("-keep class com.arthenica.** { *; }", "-dontwarn com.arthenica.**");
    console.log(`FFmpeg add-on wired in (${aar}).`);
  } else if (!hasFfmpeg) console.log("FFmpeg add-on: not found in native/android/ffmpeg-kit/ — skipped (app builds without it).");

  // ---- whisper.cpp (JNI + CMake) ----------------------------------------------------------------------------------------------
  if (hasWhisper && gradleFile && !gradle.includes("BM_WHISPER")) {
    const cpp = join(srcMain, "cpp");
    mkdirSync(cpp, { recursive: true });
    const whisperPath = whisperDir.replaceAll("\\", "/");
    writeFileSync(join(cpp, "CMakeLists.txt"), `cmake_minimum_required(VERSION 3.22.1)
project(whisper_jni LANGUAGES C CXX)
set(CMAKE_CXX_STANDARD 17)
set(GGML_OPENMP OFF CACHE BOOL "" FORCE)
set(WHISPER_BUILD_TESTS OFF CACHE BOOL "" FORCE)
set(WHISPER_BUILD_EXAMPLES OFF CACHE BOOL "" FORCE)
set(WHISPER_BUILD_SERVER OFF CACHE BOOL "" FORCE)
set(BUILD_SHARED_LIBS OFF CACHE BOOL "" FORCE)
add_subdirectory("${whisperPath}" whisper_build)
add_library(whisper_jni SHARED whisper_jni.cpp)
target_include_directories(whisper_jni PRIVATE "${whisperPath}/include" "${whisperPath}/ggml/include")
target_link_libraries(whisper_jni whisper log android)
`);
    const m = jniMangle(pkg);
    writeFileSync(join(cpp, "whisper_jni.cpp"), `// Generated by scripts/native-addons.mjs — JNI glue over the whisper.cpp C API (same calls as the official whisper.android example).
#include <jni.h>
#include <cstring>
#include "whisper.h"

#define FN(name) Java_${m}_WhisperNative_##name
extern "C" {
JNIEXPORT jlong JNICALL FN(initContext)(JNIEnv *env, jobject, jstring path) {
  const char *p = env->GetStringUTFChars(path, nullptr);
  whisper_context_params cp = whisper_context_default_params();
  cp.use_gpu = false;
  whisper_context *ctx = whisper_init_from_file_with_params(p, cp);
  env->ReleaseStringUTFChars(path, p);
  return (jlong) ctx;
}
JNIEXPORT void JNICALL FN(freeContext)(JNIEnv *, jobject, jlong h) { if (h) whisper_free((whisper_context *) h); }
JNIEXPORT jint JNICALL FN(fullTranscribe)(JNIEnv *env, jobject, jlong h, jfloatArray audio, jstring lang, jint threads) {
  auto *ctx = (whisper_context *) h;
  jfloat *data = env->GetFloatArrayElements(audio, nullptr);
  jsize n = env->GetArrayLength(audio);
  const char *l = env->GetStringUTFChars(lang, nullptr);
  whisper_full_params p = whisper_full_default_params(WHISPER_SAMPLING_GREEDY);
  p.print_realtime = false; p.print_progress = false; p.print_timestamps = false; p.print_special = false;
  p.translate = false; p.no_context = true; p.n_threads = threads; p.language = l;
  int rc = whisper_full(ctx, p, data, n);
  env->ReleaseStringUTFChars(lang, l);
  env->ReleaseFloatArrayElements(audio, data, JNI_ABORT);
  return rc;
}
JNIEXPORT jint JNICALL FN(segmentCount)(JNIEnv *, jobject, jlong h) { return whisper_full_n_segments((whisper_context *) h); }
JNIEXPORT jlong JNICALL FN(segmentStart)(JNIEnv *, jobject, jlong h, jint i) { return whisper_full_get_segment_t0((whisper_context *) h, i); }
JNIEXPORT jlong JNICALL FN(segmentEnd)(JNIEnv *, jobject, jlong h, jint i) { return whisper_full_get_segment_t1((whisper_context *) h, i); }
// Bytes, not NewStringUTF: a segment can end mid-character, and invalid UTF-8 makes the JVM abort. Kotlin decodes leniently.
JNIEXPORT jbyteArray JNICALL FN(segmentText)(JNIEnv *env, jobject, jlong h, jint i) {
  const char *t = whisper_full_get_segment_text((whisper_context *) h, i);
  jsize len = t ? (jsize) strlen(t) : 0;
  jbyteArray out = env->NewByteArray(len);
  if (len) env->SetByteArrayRegion(out, 0, len, (const jbyte *) t);
  return out;
}
}
`);
    writeFileSync(join(javaDir, "WhisperNative.kt"), `package ${pkg}

import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder

/** Generated by scripts/native-addons.mjs. whisper.cpp through JNI; the model path comes from the app's download manager. */
object WhisperNative {
    init { System.loadLibrary("whisper_jni") }
    private external fun initContext(path: String): Long
    private external fun freeContext(h: Long)
    private external fun fullTranscribe(h: Long, audio: FloatArray, lang: String, threads: Int): Int
    private external fun segmentCount(h: Long): Int
    private external fun segmentStart(h: Long, i: Int): Long
    private external fun segmentEnd(h: Long, i: Int): Long
    private external fun segmentText(h: Long, i: Int): ByteArray

    /** 16 kHz mono 16-bit PCM WAV (what the app's FFmpeg step produces) -> floats. Walks the chunks, so extra LIST chunks are fine. */
    private fun readWav(path: String): FloatArray {
        val bytes = File(path).readBytes()
        val bb = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN)
        var pos = 12
        while (pos + 8 <= bytes.size) {
            val id = String(bytes, pos, 4, Charsets.US_ASCII)
            val size = bb.getInt(pos + 4)
            if (id == "data") {
                val n = minOf(size, bytes.size - pos - 8) / 2
                return FloatArray(n) { bb.getShort(pos + 8 + it * 2) / 32768f }
            }
            pos += 8 + size + (size and 1)
        }
        throw IllegalArgumentException("The prepared audio has no sound data.")
    }

    fun transcribe(model: String, wav: String, language: String): JSONArray {
        val audio = readWav(wav)
        val h = initContext(model)
        if (h == 0L) throw IllegalStateException("The speech model couldn't be opened. Delete it and download it again.")
        try {
            val threads = Runtime.getRuntime().availableProcessors().coerceIn(2, 6)
            if (fullTranscribe(h, audio, language, threads) != 0) throw IllegalStateException("The speech engine stopped before finishing.")
            val out = JSONArray()
            for (i in 0 until segmentCount(h)) {
                val text = String(segmentText(h, i), Charsets.UTF_8).trim()
                if (text.isEmpty()) continue
                out.put(JSONObject().put("start", segmentStart(h, i) / 100.0).put("end", segmentEnd(h, i) / 100.0).put("text", text))
            }
            return out
        } finally {
            freeContext(h)
        }
    }
}
`);
    const ext = gradleFile.endsWith(".kts")
      ? `    externalNativeBuild { cmake { path = file("src/main/cpp/CMakeLists.txt"); version = "3.22.1" } } // BM_WHISPER\n`
      : `    externalNativeBuild { cmake { path file('src/main/cpp/CMakeLists.txt'); version '3.22.1' } } // BM_WHISPER\n`;
    gradle = gradle.replace(/\n(\s*)buildTypes\s*\{/, (m, ws) => `\n${ext}${m.slice(1)}`);
    keep.push(`-keep class ${pkg}.WhisperNative { *; }`);
    console.log("whisper.cpp add-on wired in.");
  } else if (!hasWhisper) console.log("whisper.cpp add-on: native/android/whisper.cpp/ not found — skipped (app builds without it).");

  if (gradleFile) writeFileSync(gradleFile, gradle);
  if (keep.length) writeFileSync(proguard, (existsSync(proguard) ? readFileSync(proguard, "utf8") : "") + `\n# BlackMusic native add-ons\n${keep.join("\n")}\n`);
  return { hasFfmpeg, hasWhisper };
}
